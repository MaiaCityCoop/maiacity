import { test } from 'vitest';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
import * as THREE from 'three';
import { fakeRenderer } from './fakegl.js';
import { bakeOf, nodeOf } from './index.js';
(globalThis as any).self ??= globalThis;
test('bake shader', async () => {
	const { r, shaders } = await (fakeRenderer as any)();
	const scene = new THREE.Scene(), camera = new THREE.OrthographicCamera();
	const src: any = nodeOf(new THREE.MeshStandardMaterial({ color: 0x406020, map: new THREE.DataTexture(new Uint8Array(4), 1, 1) }));
	const { albedo, normal } = bakeOf(src);
	const mesh = new THREE.InstancedMesh(new THREE.BoxGeometry(), albedo, 2);
	scene.add(mesh);
	const t = new THREE.RenderTarget(8, 8);
	r.setRenderTarget(t);
	r.render(scene, camera);
	mesh.material = normal;
	r.render(scene, camera);
	require('node:fs').writeFileSync('/tmp/claude-0/shots/bake-shaders.txt', shaders.join('\n\n=========\n\n'));
	const frag = shaders.filter((s: string) => s.includes('fragColor') || s.includes('@fragment'));
	console.log(frag.map((s: string) => s.split('\n').filter((l: string) => /DiffuseColor|fragColor|Output|normalView|nodeVar.*=.*texture/.test(l)).slice(-14).join('\n')).join('\n=========\n'));
});
